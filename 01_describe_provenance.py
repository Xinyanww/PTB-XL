"""
Step 1 — Describe label provenance.

Question: how are PTB-XL's diagnostic labels generated, and is the
generating process the same across the dataset?

Outputs
  results/01_fold_by_review.csv
"""

import pandas as pd

from common import RESULTS_DIR, ensure_dirs, load_ptbxl, pct, section

ensure_dirs()
df = load_ptbxl()

section("1. Records and patients")
print(f"records : {len(df):,}")
print(f"patients: {df['patient_id'].nunique():,}")

section("2. Documented human validation")
n_unrev = (~df["reviewed"]).sum()
print(f"no documented human validation: {n_unrev:,} ({pct(n_unrev / len(df))})")

section("3. Unreviewed records are all machine-generated reports")
print(pd.crosstab(df["initial_autogenerated_report"], df["reviewed"],
                  margins=True).to_string())
print("\n'validated_by' missing among unreviewed records:",
      pct(df.loc[~df["reviewed"], "validated_by"].isna().mean()))

section("4. Unreviewed records by official fold")
fold = pd.crosstab(df["strat_fold"], df["reviewed"])
fold.columns = ["unreviewed", "reviewed"]
fold["share_unreviewed"] = fold["unreviewed"] / fold.sum(axis=1)
print(fold.assign(share_unreviewed=fold["share_unreviewed"].map(pct)).to_string())

train = fold.loc[1:8]
print(f"\nfolds 1-8 (training): {pct(train['unreviewed'].sum() / train.sum(axis=1).sum())} unreviewed")
print(f"folds 9-10 (val/test): {fold.loc[9:10, 'unreviewed'].sum()} unreviewed records")
fold.to_csv(RESULTS_DIR / "01_fold_by_review.csv")

section("5. Where the unreviewed records come from")
unrev = df[~df["reviewed"]]
print(f"share of unreviewed records from site {0} / CS100: "
      f"{pct(unrev['in_unreviewed_block'].mean())} "
      f"({unrev['in_unreviewed_block'].sum():,} of {len(unrev):,})")
print(f"share of that site/device block that is unreviewed: "
      f"{pct((~df.loc[df['in_unreviewed_block'], 'reviewed']).mean())}")
print(f"unreviewed records outside that block: {(~unrev['in_unreviewed_block']).sum()}")

print("""
Reading:
  Label provenance is not a record-level variable with useful variation.
  It is almost exactly one site on one device. Any comparison of
  reviewed vs unreviewed records is therefore also a comparison of sites,
  devices, time periods, and patient populations. Step 2 makes this concrete.
""")
